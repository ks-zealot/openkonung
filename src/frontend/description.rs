/// Description record for a `NEWH_HIT` region, following the original hover
/// normalisation (`FUN_00436214` case 2): `0..=19` map to themselves and the
/// stat steppers `25..=32` map to rows `7..=10`; everything else is `None`.
pub fn description_for_region(region: usize) -> Option<&'static str> {
    match region {
        0..=19 => DESCRIPTIONS.get(region).copied(),
        25..=32 => DESCRIPTIONS.get(7 + (region - 25) / 2).copied(),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// All twenty description records are present, non-empty and verbatim.
    #[test]
    fn all_twenty_records_are_present_and_non_empty() {
        assert_eq!(DESCRIPTIONS.len(), 20);
        for (i, text) in DESCRIPTIONS.iter().enumerate() {
            assert!(!text.trim().is_empty(), "record {i}");
        }
        assert!(DESCRIPTIONS[0].starts_with("Герой Северного клана"));
        assert!(DESCRIPTIONS[15].starts_with("Мастерство владения мечом"));
    }

    /// Steppers `25..=32` normalise to stat rows `7..=10`; `20..=24` and `33+`
    /// have no record, so the previous description stays on screen.
    #[test]
    fn hover_normalisation_matches_original() {
        for r in 0..=19 {
            assert_eq!(description_for_region(r), Some(DESCRIPTIONS[r]));
        }
        assert_eq!(description_for_region(25), Some(DESCRIPTIONS[7]));
        assert_eq!(description_for_region(26), Some(DESCRIPTIONS[7]));
        assert_eq!(description_for_region(27), Some(DESCRIPTIONS[8]));
        assert_eq!(description_for_region(28), Some(DESCRIPTIONS[8]));
        assert_eq!(description_for_region(29), Some(DESCRIPTIONS[9]));
        assert_eq!(description_for_region(30), Some(DESCRIPTIONS[9]));
        assert_eq!(description_for_region(31), Some(DESCRIPTIONS[10]));
        assert_eq!(description_for_region(32), Some(DESCRIPTIONS[10]));
        for r in [20, 21, 22, 23, 24, 33] {
            assert_eq!(description_for_region(r), None, "region {r}");
        }
    }
}
