#!/usr/bin/env python3
"""Generate exact HUD/map tables from the original `konung.res`.

Source of truth (VA = 0x400000 + section RVA):

* HUD icon reset table / positions      `0x45AEA0` (7 x 16 bytes)
* HUD icon hit-test off/byte tables     `0x457740`/`0x45437C` (800)
                                        `0x456FC0`/`0x4523E4` (640)
  consumed by `FUN_00438900(x, y, off_table, byte_table)`
* world-map row offsets                 `0x456A1C` (361 x u32)
* world-map runs                        `0x450EBC` ((location, width) pairs,
                                        width 0 terminates a row)
* world-map reserved locations          `0x45AE30` (56 bytes)

Run from the repository root:

    python web/tools/gen_ui_tables.py

It writes `web/src/hud/buttons_data.rs` and `web/src/world_map/data.rs`.
Do not hand-edit the generated files.
"""

from __future__ import annotations

import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EXE = ROOT / "konung.res"
OUT_HUD = ROOT / "web" / "src" / "hud" / "buttons_data.rs"
OUT_MAP = ROOT / "web" / "src" / "world_map" / "data.rs"

# PE section layout of konung.res (verified): BEGTEXT RVA 0x10000/raw 0x400,
# DGROUP RVA 0x50000/raw 0x36200. Image base 0x400000.
BASE = 0x400000
DATA_RVA = 0x50000
DATA_RAW = 0x36200
TEXT_RVA = 0x10000
TEXT_RAW = 0x400


def file_offset(va: int) -> int:
    if va >= BASE + DATA_RVA:
        return DATA_RAW + (va - (BASE + DATA_RVA))
    return TEXT_RAW + (va - (BASE + TEXT_RVA))


def u8(d: bytes, va: int) -> int:
    return d[file_offset(va)]


def u16(d: bytes, va: int) -> int:
    return struct.unpack_from("<H", d, file_offset(va))[0]


def u32(d: bytes, va: int) -> int:
    return struct.unpack_from("<I", d, file_offset(va))[0]


def i32(d: bytes, va: int) -> int:
    return struct.unpack_from("<i", d, file_offset(va))[0]


def icon_hits(d: bytes, off_table: int, byte_table: int, panel_w: int):
    """Rows with HUD button commands (1..=7), clipped to the left panel."""
    rows = []
    for y in range(600):
        off = i32(d, off_table + y * 4)
        if off < 0:
            continue
        p = byte_table + off
        runs = []
        any_button = False
        while True:
            value = u8(d, p)
            width = u8(d, p + 1)
            if width == 0:
                runs.append((value, 0))
                break
            runs.append((value, width))
            if 1 <= value <= 7:
                any_button = True
            p += 2
        if not any_button:
            continue

        # Clip the row to the left panel (the original hit table continues into
        # inventory/scroll rows that the remake handles separately).
        clipped = []
        x = 0
        for value, width in runs:
            if width == 0:
                if x < panel_w:
                    clipped.append((value, 0))
                break
            take = min(width, panel_w - x)
            if take <= 0:
                break
            clipped.append((value, take))
            x += take
            if x >= panel_w:
                break
        if clipped:
            rows.append((y, clipped))
    return rows


def rust_runs(rows) -> str:
    out = []
    for y, runs in rows:
        pairs = ", ".join(f"({v}u8, {w}u16)" for v, w in runs)
        out.append(f"    ({y}i16, &[{pairs}]),")
    return "\n".join(out)


def main() -> None:
    d = EXE.read_bytes()

    # Positions: 7 entries of {x640,y640,x800,y800}.
    positions = []
    for i in range(7):
        base = 0x45AEA0 + i * 16
        positions.append(
            (
                i32(d, base + 0),
                i32(d, base + 4),
                i32(d, base + 8),
                i32(d, base + 12),
            )
        )

    hits_640 = icon_hits(d, 0x456FC0, 0x4523E4, 112)
    hits_800 = icon_hits(d, 0x457740, 0x45437C, 140)

    hud = f"""//! Generated by `web/tools/gen_ui_tables.py` from `konung.res`.
//!
//! Exact original HUD button geometry:
//! * positions `0x45AEA0` (7 x {{x640,y640,x800,y800}}),
//! * hit tables `0x456FC0`/`0x4523E4` (640) and `0x457740`/`0x45437C` (800),
//!   consumed by `FUN_00438900(x, y, off_table, byte_table)`.
//!
//! Row runs are `(button_code, width)`; a width of 0 terminates the row. Only
//! rows containing a HUD button code (1..=7) and columns inside the left panel
//! are emitted. Do not hand-edit.

/// `(x640, y640, x800, y800)` per icon slot; slot 0 is the weapon plaque and
/// slots 1..=6 are stance, map, halt, engage, quest log and character screen.
pub const ICON_POS: [(i32, i32, i32, i32); 7] = [
{chr(10).join(f"    ({a}, {b}, {c}, {e})," for a, b, c, e in positions)}
];

pub const ICON_HITS_640: &[(i16, &[(u8, u16)])] = &[
{rust_runs(hits_640)}
];

pub const ICON_HITS_800: &[(i16, &[(u8, u16)])] = &[
{rust_runs(hits_800)}
];
"""
    OUT_HUD.parent.mkdir(parents=True, exist_ok=True)
    OUT_HUD.write_text(hud, encoding="utf-8")

    # World map: 361 rows of (location, width) runs.
    row_count = 361
    rows = []
    for r in range(row_count):
        off = i32(d, 0x456A1C + r * 4)
        p = 0x450EBC + off
        runs = []
        while True:
            value = u8(d, p)
            width = u8(d, p + 1)
            runs.append((value, width))
            if width == 0:
                break
            p += 2
        rows.append(runs)

    reserved = [u8(d, 0x45AE30 + i) for i in range(56)]
    map_src = f"""//! Generated by `web/tools/gen_ui_tables.py` from `konung.res`.
//!
//! World-map mask:
//! * row offsets `0x456A1C` (361 x u32),
//! * runs `0x450EBC` (`(location_index, width)`, width 0 terminates),
//! * unrevealable locations `0x45AE30` (56 bytes).
//! Drawn by `FUN_00428390`; 361 rows x 502 px. Do not hand-edit.

pub const MAP_W: usize = 502;
pub const MAP_H: usize = 361;

pub const MAP_ROWS: &[&[(u8, u16)]] = &[
{chr(10).join("    &[" + ", ".join(f"({v}u8, {w}u16)" for v, w in row) + "]," for row in rows)}
];

/// Reserved / unrevealable location slots (`0x45AE30`).
pub const MAP_RESERVED: [u8; 56] = [
{chr(10).join("    " + ", ".join(str(b) for b in reserved[i:i+16]) + "," for i in range(0, 56, 16))}
];
"""
    OUT_MAP.parent.mkdir(parents=True, exist_ok=True)
    OUT_MAP.write_text(map_src, encoding="utf-8")

    print(f"wrote {OUT_HUD} ({len(hits_640)}/640, {len(hits_800)}/800 rows)")
    print(f"wrote {OUT_MAP} ({row_count} rows)")


if __name__ == "__main__":
    main()
